/** Parent-facing educational atlas, separate from signed activity packs.
 * CDC ages describe skills most children (75%+) have by that age, not averages
 * or personal deadlines. No child age, health score or readiness inference. */
export type MilestoneCategory = 'connection' | 'communication' | 'movement' | 'discovery' | 'independence';
export const MILESTONE_CATEGORIES: readonly { id: MilestoneCategory; label: string }[] = [
  { id: 'connection', label: 'Blízkost' }, { id: 'communication', label: 'Řeč a gesta' },
  { id: 'movement', label: 'Pohyb' }, { id: 'discovery', label: 'Objevování' },
  { id: 'independence', label: 'Samostatnost' },
];
export type MilestoneDefinition = {
  id: string; title: string; category: MilestoneCategory; referenceMonths: number;
  description: string; support: readonly string[];
  age: { kind: 'cdc' | 'who' | 'dental'; label: string; explanation: string };
  source: { label: string; url: string; checkedOn: string };
};
const CHECKED_ON = '2026-11-13';
const CDC_AGES: Readonly<Record<number, string>> = {
  2: '2-months', 4: '4-months', 6: '6-months', 9: '9-months', 12: '1-year',
  15: '15-months', 18: '18-months', 24: '2-years', 30: '30-months',
  36: '3-years', 48: '4-years', 60: '5-years',
};
