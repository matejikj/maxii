export const MILESTONE_SUPPORT_NOTE = 'Nabízejte příležitosti při běžné hře, bez zkoušení a tlaku. Řiďte se zájmem dítěte a při únavě udělejte pauzu. Pokud máte obavy, některá dovednost se neobjevuje nebo dítě ztrácí to, co už umělo, proberte to s pediatrem. U předčasně narozených dětí se o korigovaném věku poraďte s pediatrem.';
function m(id: string, title: string, category: MilestoneCategory, months: number, description: string, ...support: string[]): MilestoneDefinition {
  return { id, title, category, referenceMonths: months, description, support,
    age: { kind: 'cdc', label: months < 24 ? `Orientačně: ${months} měsíců` : `Orientačně: ${months === 30 ? '2,5' : months / 12} ${months === 60 ? 'let' : months === 30 ? 'roku' : 'roky'}`,
      explanation: 'Referenční věk CDC: tuto dovednost v uvedeném věku zvládá alespoň 75 % dětí. Nejde o průměrný věk prvního pokusu ani o individuální termín.' },
    source: { label: `CDC · vývojové milníky (${months} měsíců)`, url: `https://www.cdc.gov/act-early/milestones/${CDC_AGES[months]}.html`, checkedOn: CHECKED_ON } };
}

